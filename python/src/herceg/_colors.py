_HEX = re.compile(r"#(?:[0-9a-fA-F]{3,4}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})")
# rgb(), hsl(), and other functions (color-mix(), var()), which SVG passes on.
_FUNCTION = re.compile(r"[a-zA-Z-]+\(.*\)", re.DOTALL)


def is_color(value: str) -> bool:
    """Whether ``value`` is a CSS color: hex, a function such as ``rgb()``, or a name."""
    text = value.strip()
    return (
        bool(_HEX.fullmatch(text) or _FUNCTION.fullmatch(text))
        or text.lower() in _NAMES
        or text.lower() in ("transparent", "currentcolor")
    )
